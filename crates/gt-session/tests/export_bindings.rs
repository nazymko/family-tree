#![allow(clippy::unwrap_used)]
//! TypeScript bindings for every wire type.
//!
//! Without arguments this test FAILS when `app/src/lib/api/generated/` differs from what the
//! Rust types produce. To regenerate the committed files run
//! `UPDATE_BINDINGS=1 cargo test -p gt-session --test export_bindings`.

use gt_session::*;
use std::collections::BTreeMap;
use std::path::{Path, PathBuf};
use ts_rs::{Config, TS};

fn committed_dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../../app/src/lib/api/generated")
}

fn read_dir_files(dir: &Path) -> BTreeMap<String, String> {
    let mut out = BTreeMap::new();
    let Ok(rd) = std::fs::read_dir(dir) else {
        return out;
    };
    for e in rd.flatten() {
        if e.path().extension().is_some_and(|x| x == "ts") {
            let text = std::fs::read_to_string(e.path())
                .unwrap()
                .replace("\r\n", "\n");
            out.insert(e.file_name().to_string_lossy().into_owned(), text);
        }
    }
    out
}

