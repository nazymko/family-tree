#[test]
fn generated_types_match_committed_files() {
    let fresh_dir = tempfile::tempdir().unwrap();
    export_all(fresh_dir.path());
    let fresh = read_dir_files(fresh_dir.path());
    assert!(fresh.contains_key("PersonRef.ts") && fresh.contains_key("index.ts"));

    let target = committed_dir();
    if std::env::var_os("UPDATE_BINDINGS").is_some() {
        std::fs::create_dir_all(&target).unwrap();
        for old in read_dir_files(&target).keys() {
            std::fs::remove_file(target.join(old)).unwrap();
        }
        for (name, text) in &fresh {
            std::fs::write(target.join(name), text).unwrap();
        }
        return;
    }
    let committed = read_dir_files(&target);
    let missing: Vec<_> = fresh
        .keys()
        .filter(|k| !committed.contains_key(*k))
        .collect();
    let stale: Vec<_> = committed
        .keys()
        .filter(|k| !fresh.contains_key(*k))
        .collect();
    let changed: Vec<_> = fresh
        .iter()
        .filter(|(k, v)| committed.get(*k).is_some_and(|c| c != *v))
        .map(|(k, _)| k)
        .collect();
    assert!(
        missing.is_empty() && stale.is_empty() && changed.is_empty(),
        "app/src/lib/api/generated is out of date (missing {missing:?}, stale {stale:?}, changed {changed:?}). \
         Run: UPDATE_BINDINGS=1 cargo test -p gt-session --test export_bindings"
    );
}

#[test]
fn camel_case_wire_format() {
    let r = PersonRef {
        id: uuid::Uuid::nil(),
        name: "A".into(),
        lifespan: String::new(),
        sex: SexKind::Female,
        living: true,
        private: false,
    };
    let row = PersonRow {
        person: r,
        surname: String::new(),
        given: String::new(),
        birth: String::new(),
        death: String::new(),
        source_count: 2,
        changed: 5,
    };
    let v = serde_json::to_value(&row).unwrap();
    assert_eq!(v["sourceCount"], 2);
    assert_eq!(v["name"], "A");
    assert_eq!(v["sex"], "female");
    let e = serde_json::to_value(ApiError::new(ErrorCode::NotFound, "x")).unwrap();
    assert_eq!(e["code"], "not_found");
    let q: PersonQuery = serde_json::from_str(
        r#"{"sort":"given","desc":true,"text":"","living":"deceased","noSource":true,"noBirthDate":false,"privateOnly":false}"#,
    )
    .unwrap();
    assert_eq!(q.sort, SortKey::Given);
    assert!(q.no_source);
}
